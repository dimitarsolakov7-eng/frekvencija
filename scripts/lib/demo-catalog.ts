/** Keys from ANNOUNCEMENT_TEMPLATES (src/lib/announcements/templates.ts), in playback-relevant order. */
export const DEMO_ANNOUNCEMENT_TEMPLATE_KEYS: readonly AnnouncementTemplateKey[] = ["welcome_enjoy", "station_listening", "good_music"];

export interface DemoAnnouncement {
  /** Stable file id, e.g. "emeraldbar-welcome-enjoy". */
  id: string;
  businessKey: DemoBusinessKey;
  templateKey: AnnouncementTemplateKey;
  /** Human label of the template, e.g. "Welcome". */
  label: string;
  placement: "welcome" | "rotation" | "both";
  /** Display wording with the real names. */
  text: string;
  /** Wording with pronunciation spellings, or null when identical to `text`. */
  spokenText: string | null;
  /** Placeholder melody for this announcement (distinct per business and per announcement). */
  chime: ChimeOptions;
}

/** The chime variant for the n-th announcement of a business: 4 rising/falling notes, the first 2, or 3 reversed. */
function chimeVariant(business: DemoBusiness, index: number): ChimeOptions {
  const notes = business.chime.notesHz;
  const variants = [notes, notes.slice(0, 2), [...notes.slice(0, 3)].reverse()];
  return { notesHz: variants[index % variants.length], timbre: business.chime.timbre, spacingSeconds: 0.32 };
}

export function demoAnnouncementsFor(business: DemoBusiness): DemoAnnouncement[] {
  return DEMO_ANNOUNCEMENT_TEMPLATE_KEYS.map((templateKey, index) => {
    const template = getAnnouncementTemplate(templateKey);
    if (!template) throw new Error(`Announcement template "${templateKey}" does not exist in src/lib/announcements/templates.ts`);
    const wording = renderAnnouncementWording(template.text, business);
    return {
      id: `${business.key}-${templateKey.replace(/_/g, "-")}`,
      businessKey: business.key,
      templateKey,
      label: template.label,
      placement: template.defaultPlacement,
      text: wording.text,
      spokenText: wording.spokenText,
      chime: chimeVariant(business, index),
    };
  });
}

export function findDemoBusiness(key: string): DemoBusiness | undefined {
  return DEMO_BUSINESSES.find((business) => business.key === key);
}

export function findDemoGenre(slug: string): DemoGenre | undefined {
  return DEMO_GENRES.find((genre) => genre.slug === slug);
}

