export interface DemoUserDefinition {
  /** Environment variable that overrides the email. */
  envVar: string;
  defaultEmail: string;
  fullName: string;
}

export interface DemoBusiness {
  key: DemoBusinessKey;
  /** The names the spec and the demo announcements use; they stay exactly as written (no "(example)"). */
  name: string;
  stationName: string;
  namePronunciation: string | null;
  stationNamePronunciation: string | null;
  /** businesses.business_type, shown under the name in the admin list and on the venue's Account page. */
  businessType: BusinessTypeEnum;
  /**
   * Seed marker: an example.com address that labels the row as demo data. It is the venue's visible
   * "Contact email" in the admin, and searching the business list for "example.com" finds the demo
   * venues (the businesses table has no notes column to carry an "example" label). The seed only ever
   * reuses a business whose name AND contact email match, so it never touches a real venue with the
   * same name. The announcement frequency is not set here: new demo venues get the platform default
   * (platform_settings.default_announcement_every_n_tracks), like venues added in the admin.
   */
  contactEmail: string;
  /** Genres with available_to_all = false that this venue gets an access row for. */
  exclusiveGenreSlugs: string[];
  /** Preferred Windows SAPI voice for the demo announcements. */
  sapiVoice: string;
  /** Placeholder melody when SAPI is unavailable (distinct per business). */
  chime: Pick<ChimeOptions, "notesHz" | "timbre">;
  user: DemoUserDefinition;
}

