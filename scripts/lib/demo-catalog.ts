export interface DemoTrack {
  /** 1-based position across all genres (the number in the title). */
  number: number;
  /** Stable file id, e.g. "test-loop-01-house". */
  id: string;
  title: string;
  genre: DemoGenre & { style: MusicStyle };
  /** Deterministic synth seed. */
  seed: number;
  /** Target length, 21–38 s; the synth rounds it to whole bars, so files are 20–40 s long. */
  targetSeconds: number;
}

/** Every demo loop, numbered 01…N across the genres in sort order. */
export function listDemoTracks(): DemoTrack[] {
  const tracks: DemoTrack[] = [];
  for (const genre of DEMO_GENRES) {
    const style = genre.style;
    if (genre.demoTracks === 0) continue;
    if (!style) throw new Error(`Genre "${genre.slug}" has demo tracks but no synth style`);
    for (let k = 0; k < genre.demoTracks; k++) {
      const number = tracks.length + 1;
      const padded = String(number).padStart(2, "0");
      tracks.push({
        number,
        id: `test-loop-${padded}-${genre.slug}`,
        title: `Test Loop ${padded} — ${genre.name} (synthetic)`,
        genre: { ...genre, style },
        seed: number * 7919,
        // Short loops so "announcement after every 4 completed tracks" can be tested in minutes.
        targetSeconds: 21 + ((number * 11) % 18),
      });
    }
  }
  return tracks;
}
